// =================================================================
// 2. LEARNING & EXPLAIN MODELS
// =================================================================

enum class LearningLevel(val displayName: String, val promptDescription: String) {
    BEGINNER("Beginner", "Explain in simple, everyday language using intuitive analogies without heavy technical jargon."),
    INTERMEDIATE("Intermediate", "Provide clear technical depth, real-world practical examples, and core working principles."),
    ADVANCED("Advanced", "Provide rigorous conceptual breakdown, mechanisms, edge cases, and formal terminology.")
}

data class LessonSection(
    val heading: String,
    val content: String
)

data class LessonQuiz(
    val question: String,
    val options: List<String>,
    val correctOptionIndex: Int,
    val explanation: String,
    val hint: String? = null
)

/** A named component of the topic (e.g. "Anode" → "releases electrons"), rendered as a parts diagram. */
data class LessonPart(
    val name: String,
    val role: String
)

/** A glossary entry generated for the lesson. */
data class LessonTerm(
    val term: String,
    val meaning: String
)

/**
 * A lesson generated by the on-device model. Every field is model output; the UI renders each
 * non-empty field as its own block (key points, process diagram, parts diagram, concept cards, quizzes).
 */
data class StructuredLesson(
    val topic: String,
    val level: LearningLevel,
    val title: String,
    val overview: String,
    val sections: List<LessonSection>,
    val practicalExample: String,
    val quizzes: List<LessonQuiz> = emptyList(),
    val keyPoints: List<String> = emptyList(),
    val flowSteps: List<String> = emptyList(),
    val parts: List<LessonPart> = emptyList(),
    val terms: List<LessonTerm> = emptyList()
) {
    /** First knowledge check, kept for callers that only need one. */
    val quiz: LessonQuiz? get() = quizzes.firstOrNull()

    val hasContent: Boolean
        get() = overview.isNotBlank() || keyPoints.isNotEmpty() || sections.isNotEmpty() || flowSteps.isNotEmpty()
}

/** The learner's state for one knowledge check. Persisted with the lesson so progress survives restarts. */
data class QuizProgress(
    val selectedIndex: Int? = null,
    val submitted: Boolean = false,
    val attempts: Int = 0
) {
    fun isCorrect(quiz: LessonQuiz): Boolean = submitted && selectedIndex == quiz.correctOptionIndex
}

